/**
 * Убирает редакторскую нумерацию раздела перед заголовком.
 * Сам заголовок в документе остаётся без изменений: нормализованная строка
 * используется только в оглавлении и в URL-якоре.
 */
export function normalizeHeadingText(text: string): string {
  return text
    .trim()
    .replace(/^(?:(?:\d+\.)+\d*\.?|\d+[.)])\s+/, '')
    .trim()
}
